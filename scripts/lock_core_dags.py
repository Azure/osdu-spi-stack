"""Resolve core's binary lock and hash the OSDU wheels from their find-links pages."""

import hashlib
import re
import subprocess
import tempfile
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
DAGS = ROOT / "software" / "stacks" / "osdu" / "dags"
CONSTRAINTS = (
    "https://raw.githubusercontent.com/apache/airflow/constraints-3.2.2/constraints-3.13.txt"
)
CONSTRAINTS_SHA256 = "b3e3c347186f40738abb0e0529affb7ac9f7de8e3cb6bbc8df7be66a5bcfcfd0"


def read(url: str) -> bytes:
    with urlopen(url, timeout=60) as response:
        return response.read()


class Links(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.urls: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag == "a":
            self.urls.extend(value for key, value in attrs if key == "href" and value)


def wheel_hash(page: str, name: str, version: str) -> str:
    parser = Links()
    parser.feed(read(page).decode())
    filename = f"{name.replace('-', '_')}-{version}-py3-none-any.whl"
    urls = {url for url in parser.urls if urlsplit(url).path.endswith("/" + filename)}
    if len(urls) != 1:
        raise ValueError(f"{page}: expected one {filename}, found {len(urls)}")
    (url,) = urls
    origin, target = urlsplit(page), urlsplit(url)
    if target.scheme != "https" or target.netloc != origin.netloc:
        raise ValueError(f"{name}: wheel link left its registry")
    digest = hashlib.sha256(read(url)).hexdigest()
    if target.fragment != "sha256=" + digest:
        raise ValueError(f"{filename}: downloaded SHA-256 differs from registry")
    print(f"{filename}: sha256 {digest}")
    return digest


def package(line: str) -> str:
    return re.split(r"[=<>!~;\s]", line, maxsplit=1)[0].lower().replace("_", "-")


def compile_lock(constraints: list[str], overrides: Path) -> str:
    with tempfile.TemporaryDirectory() as scratch:
        constraints_file = Path(scratch) / "constraints.txt"
        constraints_file.write_text("\n".join(constraints) + "\n", encoding="utf-8")
        return subprocess.run(
            [
                "uv",
                "--no-config",
                "pip",
                "compile",
                str(DAGS / "requirements.in"),
                "--constraint",
                str(constraints_file),
                "--override",
                str(overrides),
                "--python-version",
                "3.13",
                "--python-platform",
                "linux",
                "--default-index",
                "https://pypi.org/simple/",
                "--only-binary",
                ":all:",
                "--generate-hashes",
                "--emit-find-links",
                "--emit-build-options",
                "--upgrade",
                "--no-annotate",
                "--no-header",
            ],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout


def main() -> None:
    constraints = read(CONSTRAINTS)
    if hashlib.sha256(constraints).hexdigest() != CONSTRAINTS_SHA256:
        raise ValueError("Airflow constraints changed; review the image and constraints together")
    overrides = DAGS / "overrides.txt"
    overridden = {
        package(line)
        for line in overrides.read_text(encoding="utf-8").splitlines()
        if line and not line.startswith("#")
    }
    # uv applies constraints on top of overrides, so an overridden pin must leave the constraints.
    kept = [line for line in constraints.decode().splitlines() if package(line) not in overridden]
    inputs = (DAGS / "requirements.in").read_text(encoding="utf-8")
    pages = re.findall(r"^--find-links (\S+)$", inputs, re.MULTILINE)
    pins = dict(re.findall(r"^(osdu-[a-z]+)==(\S+)$", inputs, re.MULTILINE))
    wheel_hashes = {
        name: wheel_hash(
            next(page for page in pages if page.rstrip("/").endswith("/" + name)), name, version
        )
        for name, version in pins.items()
    }
    stdout = compile_lock(kept, overrides)
    lines = [
        "# Generated by: uv run python scripts/lock_core_dags.py",
        f"# Airflow 3.2.2 / Python 3.13 constraints SHA-256: {CONSTRAINTS_SHA256}",
    ]
    for line in stdout.replace("\\\n", "").splitlines():
        if not line or line.startswith("--"):
            lines.append(line)
            continue
        pin, *options = line.split()
        name, version = pin.split("==", 1)
        hashes = sorted({option for option in options if option.startswith("--hash=sha256:")})
        # uv does not emit hashes for remote find-links wheels; verify their
        # downloaded bytes instead of trusting the resolver's unhashed pin.
        if name in wheel_hashes:
            if pins[name] != version:
                raise ValueError(f"resolver changed the reviewed pin: {pin}")
            hashes = ["--hash=sha256:" + wheel_hashes[name]]
        if not hashes:
            raise ValueError(f"{pin}: no SHA-256 hashes")
        lines.append(pin + " \\\n    " + " \\\n    ".join(hashes))
    (DAGS / "requirements.txt").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
